// ---------------------------------------------------------------------------
// INSTALL — precache the full manifest, then activate immediately.
//
// Per-entry semantics (each wrapped in try/catch — best-effort, a single 404
// never aborts installation, but every outcome is COUNTED and reported):
//   - network-first classes (HTML, ./js/, ./data/, root files): ALWAYS
//     refetched, so every SW update refreshes all code+data in the cache —
//     including files the page never requests at boot. Closes the placebo
//     hole where a lazily-fetched JSON stayed stale forever offline.
//   - cache-first classes (./vendor/, ./textures/): skipped when already
//     stored. Immutable by contract; editing one requires a CACHE_NAME bump.
//     This keeps the ~tens-of-MB texture set from being re-downloaded on
//     every deploy by every returning client.
// ---------------------------------------------------------------------------
const PRECACHE_CONCURRENCY = 8;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME);
      const counts = { fetched: 0, present: 0, failed: 0 };
      const queue = PRECACHE_URLS.slice();
      const worker = async () => {
        for (;;) {
          const url = queue.shift();
          if (url === undefined) return;
          try {
            const abs = new URL(url, self.location.href);
            if (isCacheFirstURL(abs) && await cache.match(abs.href)) {
              counts.present += 1;
              continue;
            }
            // cache:'no-cache' revalidates through any HTTP cache in the way
            // (GitHub Pages' 10-min cache, Safari heuristics) — the wire must
            // hand out the freshest build (Ipad.md §2.4, wire-first).
            const resp = await fetch(new Request(url, { cache: 'no-cache' }));
            if (!resp || !resp.ok) throw new Error('HTTP ' + (resp ? resp.status : 'null'));
            await cache.put(url, resp);
            counts.fetched += 1;
          } catch (err) {
            counts.failed += 1;
            // eslint-disable-next-line no-console
            console.warn('[SW] pre-cache miss for', url, err);
          }
        }
      };
      await Promise.all(Array.from({ length: PRECACHE_CONCURRENCY }, worker));
      // REPORT — the install-burst count is the offline-permanence witness.
      // eslint-disable-next-line no-console
      console.info(
        `[SW] precache ${CACHE_NAME} (build ${PRECACHE_BUILD}): ` +
        `${PRECACHE_URLS.length} entries — ${counts.fetched} fetched, ` +
        `${counts.present} already cached, ${counts.failed} failed`
      );
    } catch (err) {
      // eslint-disable-next-line no-console
      console.warn('[SW] install error:', err);
    }
    await self.skipWaiting();
  })());
});

// ---------------------------------------------------------------------------
// ACTIVATE — claim clients, evict stale caches.
// ---------------------------------------------------------------------------
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    try {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      );
    } catch (err) {
      // eslint-disable-next-line no-console
      console.warn('[SW] activate cleanup error:', err);
    }
    await self.clients.claim();
  })());
});

