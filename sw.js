/** Is this an HTML navigation? */
function isHTMLRequest(request) {
  if (request.mode === 'navigate') return true;
  const accept = request.headers.get('accept') || '';
  return accept.includes('text/html');
}

/** Is this a JS module fetch? */
function isJSRequest(url) {
  const p = url.pathname.toLowerCase();
  return p.endsWith('.js') || p.endsWith('.mjs');
}

/** Should this URL be served cache-first? */
function isCacheFirstURL(url) {
  if (url.pathname.includes('/vendor/')) return true;
  if (url.pathname.includes('/textures/')) return true;
  return false;
}

/**
 * Curated JSON under ./data/ — small, and edited far more often than the code
 * that reads it. These are deliberately NOT cache-first: a cache-first entry is
 * pinned until CACHE_NAME changes, so every content edit silently kept serving
 * the previously cached copy and a shipped data change could never reach a
 * returning player (a city label added to data/cities.json stayed invisible
 * through any number of reloads). Network-first keeps them fresh when online
 * and still falls back to the cached copy offline, so offline-first holds.
 */
function isDataURL(url) {
  return url.pathname.includes('/data/');
}

/** Synthetic offline response when both network and cache fail. */
function offlineResponse(url) {
  return new Response(
    `// [SW] offline — ${url.href} not available\n`,
    {
      status: 503,
      statusText: 'Offline',
      headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    }
  );
}

/**
 * Network-first: try the network, populate cache on success, fall back to
 * cache on failure, then a synthetic offline Response.
 *
 * The network fetch is bounded by a short AbortController timeout ONLY when
 * the browser reports itself offline (`!navigator.onLine`), so a dead-but-
 * connected network (captive portal, VPN with no upstream) falls back to
 * cache fast instead of blocking on the OS socket timeout. When online, the
 * fetch is unbounded so a slow-but-healthy connection still gets the latest
 * deploy rather than being force-aborted into a stale cached copy. On
 * localhost this never trips; it's insurance for remote deploys.
 *
 * IMPORTANT: clone the response BEFORE handing it to the page; `cache.put`
 * consumes the clone's body, not the original.
 */
const NETWORK_TIMEOUT_MS = 4000;

async function networkFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  // Only arm the abort timer when the browser thinks it's offline — avoids
  // aborting a slow-but-online fetch and serving stale code (see comment above).
  const controller = new AbortController();
  const timer = (typeof navigator !== 'undefined' && navigator.onLine === false)
    ? setTimeout(() => controller.abort(), NETWORK_TIMEOUT_MS)
    : null;
  try {
    const networkResponse = await fetch(request, { signal: controller.signal });
    if (networkResponse && networkResponse.ok) {
      // Clone first — do NOT await put before returning to the page.
      const copy = networkResponse.clone();
      cache.put(request, copy).catch(() => { /* ignore quota / opaque errors */ });
    }
    return networkResponse;
  } catch (_err) {
    const cached = await cache.match(request);
    if (cached) return cached;
    // Offline fallback for a version-stamped miss (x.json?v=N, core/dataUrl.js):
    // answer from the BARE precached entry, which THIS install refreshed — NOT
    // from an older stamped copy. cache.match(…, {ignoreSearch}) returns the
    // OLDEST-inserted match, so a stale x.json?v=(N-1) left by a prior online
    // session would outrank the fresh bare entry (every install cache.puts the
    // bare URL, which delete-appends it to the END of the match list). So strip
    // the query and EXACT-match the bare URL first; only then fall back to any
    // match so an unknown-query resource still resolves offline. This also lets
    // `/?shot=1`-style navigations reuse the precached './'.
    const bareURL = new URL(request.url);
    bareURL.search = '';
    const fresh = await cache.match(bareURL.href);
    if (fresh) return fresh;
    const loose = await cache.match(request, { ignoreSearch: true });
    if (loose) return loose;
    return offlineResponse(new URL(request.url));
  } finally {
    if (timer !== null) clearTimeout(timer);
  }
}

/**
 * Cache-first: serve from cache if present, otherwise fetch from network
 * and populate cache on success. Only response.ok responses are stored to
 * avoid poisoning the cache.
 */
async function cacheFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) return cached;

  try {
    const networkResponse = await fetch(request);
    if (networkResponse && networkResponse.ok) {
      const copy = networkResponse.clone();
      cache.put(request, copy).catch(() => { /* ignore */ });
    }
    return networkResponse;
  } catch (_err) {
    // Same bare-URL-first fallback as networkFirst. Vendor/textures are never
    // query-stamped, so the bare match usually equals the request; kept
    // identical so the two routes can't drift in their offline semantics.
    const bareURL = new URL(request.url);
    bareURL.search = '';
    const fresh = await cache.match(bareURL.href);
    if (fresh) return fresh;
    const loose = await cache.match(request, { ignoreSearch: true });
    if (loose) return loose;
    return offlineResponse(new URL(request.url));
  }
}

self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Non-GET requests bypass the SW entirely.
  if (request.method !== 'GET') return;

  let url;
  try {
    url = new URL(request.url);
  } catch (_err) {
    return; // malformed URL — let the browser handle it.
  }

  // Don't intercept the SW's own URL.
  if (url.pathname.endsWith('/sw.js')) return;

  // Only handle http(s) — skip chrome-extension://, data:, blob:, etc.
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return;

  // Cache-first: vendored Three.js (./vendor/) and textures — immutable blobs.
  // This MUST be checked before the JS network-first branch below, otherwise
  // vendored `.js` modules would match isJSRequest() and go network-first.
  if (isCacheFirstURL(url)) {
    event.respondWith(cacheFirst(request));
    return;
  }

  // Network-first: HTML navigations, JS modules, and ./data/ JSON (so new
  // deploys and content edits take effect on the next visit; falls back to
  // cache, then a synthetic offline Response).
  if (isHTMLRequest(request) || isJSRequest(url) || isDataURL(url)) {
    event.respondWith(networkFirst(request));
    return;
  }

  // Anything else — passthrough (don't call respondWith).
});
